def main():
    os.makedirs(OUT, exist_ok=True)
    n = 0
    for code, (name, rtl, strings) in T.items():
        merged = {k: strings.get(k) or EN[k] for k in KEYS}
        data = {"code": code, "name": name, "rtl": rtl, "strings": merged}
        path = os.path.join(OUT, f"{code}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=1, sort_keys=True)
        n += 1
    # English itself
    data = {"code": "en", "name": "English", "rtl": False, "strings": EN}
    with open(os.path.join(OUT, "en.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1, sort_keys=True)
    print(f"i18n: wrote {n+1} language files to {OUT}")

if __name__ == "__main__":
    main()
