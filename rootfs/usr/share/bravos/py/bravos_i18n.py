#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""bravos_i18n — shared i18n helper for the BraveOS python apps.

Each app namespace (settings, installer, welcome, dock, lock, osd) has
translation files at /usr/share/bravos/i18n/<app>/<lang>.conf (key=value,
UTF-8), generated by scripts/gen_i18n.py from the single source table.

tr(key, fallback_english) resolves in the app's table; anything missing
falls back to English (and then to the key itself). rtl() tells RTL apps
which direction to lay out in.

usage:
    import sys
    sys.path.insert(0, "/usr/share/bravos/py")
    from bravos_i18n import I18n
    i18n = I18n("settings")
    label = i18n.tr("st_network", "Network")
"""
import os

I18N_DIR = "/usr/share/bravos/i18n"
RTL_LANGS = {"ar", "he", "fa", "ur"}


class I18n:
    def __init__(self, app):
        self.app = app
        self.lang = "en"
        self.table = {}
        lang = os.environ.get("BRAVEOS_LANG") or os.environ.get("LANG") or "en"
        lang = lang.split(".")[0].lower()
        for cand in (lang, lang.replace("-", "_"), lang.split("_")[0],
                     lang.split("-")[0]):
            path = os.path.join(I18N_DIR, app, cand + ".conf")
            if os.path.exists(path):
                with open(path, encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if not line or line.startswith("#") or "=" not in line:
                            continue
                        k, v = line.split("=", 1)
                        self.table[k.strip()] = v.strip().strip('"').strip("'")
                self.lang = cand.split("_")[0].split("-")[0]
                break
        # merge the base language under a regional variant (pt_BR <- pt)
        base = self.lang
        if base and base != self.lang:
            path = os.path.join(I18N_DIR, app, base + ".conf")
            if os.path.exists(path):
                with open(path, encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if not line or line.startswith("#") or "=" not in line:
                            continue
                        k, v = line.split("=", 1)
                        self.table.setdefault(k.strip(),
                                              v.strip().strip('"').strip("'"))

    def tr(self, key, fallback=None):
        v = self.table.get(key)
        if v:
            return v
        return fallback if fallback is not None else key

    def rtl(self):
        return self.lang in RTL_LANGS
